    $rows = array_values(array_filter(
        $before[$conn]['rights'],
        fn ($r) => in_array((int) $r['menu_id'], $touched, true)
    ));

    $out[] = str_repeat('-', 70);
    $out[] = "-- HOST: $label   (connection `$conn`)";
