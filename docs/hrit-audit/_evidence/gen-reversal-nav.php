    $out[] = '   AND menu_id    IN (' . implode(',', $touched) . ');';
    $out[] = '';

    if ($rows === []) {
        $out[] = '-- 2. Nothing to restore: this host held no rows on these menus.';
    } else {
        $out[] = '-- 2. Put back exactly what was there, flags included.';
