    }

    $out[] = '';
    $out[] = '-- 3. Confirm before committing. Expected: ' . count($rows);
    $out[] = 'SELECT COUNT(*) AS restored FROM tblgroupwise_rights_g2g';
    $out[] = ' WHERE profile_id IN (' . implode(',', $profileIds) . ')';
    $out[] = '   AND menu_id    IN (' . implode(',', $touched) . ');';
    $out[] = '';
    $out[] = 'COMMIT;';
    $out[] = '';
}

$dest = __DIR__ . '/../_reversals/REVERSAL-2026-09-21-employee-leave-menu.sql';
