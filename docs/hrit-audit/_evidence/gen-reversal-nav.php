];

$hosts = ['mysql' => '202.47.117.220 (web.triz.co.in)', 'live' => '128.199.17.97 (lms.triz.co.in)'];

$out = [];
$out[] = '-- REVERSAL - 2026-09-21 - employee HRIT menu rights (F-209)';
$out[] = '--';
$out[] = '-- Reverses database/migrations/2026_09_21_120000_give_employees_the_leave_menu.php';
